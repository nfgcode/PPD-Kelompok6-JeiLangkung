        public static int Measure(string text, int scale = 1) => text.Length == 0 ? 0 : (text.Length * Advance - 1) * scale;

        public static void Draw<T>(PixelCanvas<T> canvas, string text, int x, int y, T value, int scale = 1) where T : struct
        {
            foreach (char raw in text)
            {
                int index = Characters.IndexOf(char.ToUpperInvariant(raw));
                if (index < 0) index = Characters.IndexOf('?');
                for (int column = 0; column < 5; column++)
                {
                    byte bits = Glyphs[index * 5 + column];
                    for (int row = 0; row < GlyphHeight; row++)
                        if ((bits >> row & 1) != 0) canvas.Rect(x + column * scale, y + row * scale, scale, scale, value);
                }
                x += Advance * scale;
            }
        }
    }
